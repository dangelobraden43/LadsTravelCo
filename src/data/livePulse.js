const iso = (d) => d.toISOString().slice(0, 10)

/* Everything still ahead of `today`. A played game removes itself. */
export function liveEvents(today = iso(new Date())) {
  return PULSE_EVENTS.filter((e) => e.date >= today)
}

/* The hook: what is on in the next `days` days, today included. */
export function upcoming(days = 7, today = iso(new Date())) {
  const end = new Date(today)
  end.setDate(end.getDate() + days)
  const endStr = iso(end)
  return PULSE_EVENTS.filter((e) => e.date >= today && e.date <= endStr)
}

export function eventsByVenue(list) {
  const m = new Map()
  list.forEach((e) => {
    if (!m.has(e.venueId)) m.set(e.venueId, [])
    m.get(e.venueId).push(e)
  })
  return m
}

export const venueById = (id) => PULSE_VENUES.find((v) => v.id === id)
