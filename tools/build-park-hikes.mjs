/* tools/build-park-hikes.mjs — GENERATES src/data/parkHikes.js.
 *
 *   node tools/build-park-hikes.mjs                 (fetches the feed: two requests)
 *   node tools/build-park-hikes.mjs --from <file>   (re-uses a saved, trimmed copy)
 *
 * The hikes on each park card are the National Park Service's own "things to do" records
 * (developer.nps.gov/api/v1/thingstodo), matched to a park by the park code on the record,
 * never by name. Titles, durations and links are the Service's, shown with that credit.
 *
 * Why not a popularity ranking: AllTrails' terms (updated Dec 17 2025, read Nov 10 2026)
 * license its material for personal, non-commercial use, bar republishing without written
 * consent, and require written permission to link to anything but its home page. So its
 * rankings are not published here.
 */
/* eslint-env node */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const now = new Date()
const TODAY = [now.getFullYear(), now.getMonth() + 1, now.getDate()]
  .map((n) => String(n).padStart(2, '0'))
  .join('-') // the local date: toISOString() is UTC and reads a day ahead in the evening
const KEY = process.env.NPS_API_KEY || 'DEMO_KEY'

async function fetchFeed() {
  const all = []
  for (let start = 0; ; start += 2000) {
    const r = await fetch(
      `https://developer.nps.gov/api/v1/thingstodo?limit=2000&start=${start}&api_key=${KEY}`,
    )
    if (!r.ok) throw new Error(`NPS feed: HTTP ${r.status}`)
    const j = await r.json()
    for (const t of j.data) {
      all.push({
        id: t.id,
        title: t.title,
        duration: t.duration,
        url: t.url,
        parks: (t.relatedParks || []).map((p) => p.parkCode),
        activities: (t.activities || []).map((a) => a.name),
      })
    }
    if (all.length >= Number(j.total) || j.data.length === 0) break
  }
  return all
}

const from = process.argv.indexOf('--from')
const feed = from > -1 ? JSON.parse(fs.readFileSync(process.argv[from + 1], 'utf8')) : await fetchFeed()
if (feed.length < 2000) throw new Error('the feed looks incomplete')

const { PARKS } = await import(pathToFileURL(path.join(ROOT, 'src/data/nationalParks.js')).href)
const out = {}
let kept = 0
for (const park of PARKS) {
  const seen = new Set()
  const hikes = feed
    .filter(
      (t) =>
        t.parks.includes(park.code) &&
        t.activities.some((a) => /Hiking/.test(a)) &&
        /^https:\/\/www\.nps\.gov\//.test(t.url || '') &&
        t.title,
    )
    .filter((t) => (seen.has(t.id) ? false : seen.add(t.id)))
    // the feed's own order, but a hike that says how long it takes comes before one that does not
    .sort((a, b) => Number(Boolean(b.duration)) - Number(Boolean(a.duration)))
    .slice(0, 3)
    .map((t) => ({ id: t.id, title: t.title.trim(), duration: (t.duration || '').trim() || null, url: t.url }))
  if (hikes.length) {
    out[park.code] = hikes
    kept += hikes.length
  }
}

fs.writeFileSync(
  path.join(ROOT, 'src/data/parkHikes.js'),
  `/* GENERATED by tools/build-park-hikes.mjs on ${TODAY}. Do not edit by hand: re-run the tool.
 * Hikes the National Park Service lists for each park, from its own "things to do" records.
 * Titles, durations and links are the Service's and are always rendered with that credit. */

export const HIKES_SOURCE = ${JSON.stringify(
    { name: 'National Park Service', url: 'https://www.nps.gov/planyourvisit/things-to-do.htm', checkedOn: TODAY },
    null,
    2,
  )}

export const PARK_HIKES = ${JSON.stringify(out, null, 2)}
`,
)
console.log(`park hikes: ${kept} hikes across ${Object.keys(out).length} of ${PARKS.length} parks`)
