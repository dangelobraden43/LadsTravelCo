/* tools/build-park-trails.mjs — GENERATES src/data/parkTrails.js.
 *
 *   node tools/build-park-trails.mjs
 *
 * Reads internal/research/parks-trails/alltrails-top3.json (collected through the AllTrails
 * connector, sorted by AllTrails' own popularity ranking, each trail kept only when
 * AllTrails' location label names that park) and writes the public data file.
 * Only names, distance, climb, difficulty, route type and a link are published, always
 * labelled as AllTrails data. No ratings, photos or review text.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'internal/research/parks-trails/alltrails-top3.json'), 'utf8'),
)
const { PARKS } = await import(pathToFileURL(path.join(ROOT, 'src/data/nationalParks.js')).href)
const codes = new Set(PARKS.map((p) => p.code))

// Parks whose trails came from more than one search, so their order is not one ranking.
const UNRANKED = new Set(['npsa'])
const CLOSED = /\s*\[CLOSED\]\s*/i

// Held off the card. Yellowstone: on the Nov 10 2026 collection AllTrails' ranking
// returned only the northern strip, because the geyser-basin trails were marked closed
// for the season. Re-collect in season before showing it.
const HOLD = new Set(['yell'])

const out = {}
const unranked = []
let kept = 0
for (const [code, trails] of Object.entries(src.parks)) {
  if (!codes.has(code)) throw new Error(`unknown park code: ${code}`)
  if (HOLD.has(code)) continue
  const clean = []
  for (const t of trails.slice(0, 3)) {
    if (!t.name || !/^https:\/\/www\.alltrails\.com\/trail\//.test(t.url || '')) {
      throw new Error(`bad trail under ${code}: ${JSON.stringify(t)}`)
    }
    if (t.url.includes('?')) throw new Error(`tracking parameters left on ${t.url}`)
    clean.push({
      id: t.id,
      // AllTrails marks a closed trail in its name; carry that as a flag, not as a title
      name: t.name.replace(CLOSED, ' ').trim(),
      closed: CLOSED.test(t.name),
      miles: Number.isFinite(t.length_miles) ? Math.round(t.length_miles * 10) / 10 : null,
      climbFeet: Number.isFinite(t.elevation_gain_feet) ? Math.round(t.elevation_gain_feet) : null,
      difficulty: t.difficulty || null,
      route: t.route_type || null,
      url: t.url,
    })
  }
  if (clean.length) {
    out[code] = clean
    kept += clean.length
    if (UNRANKED.has(code)) unranked.push(code)
  }
}

fs.writeFileSync(
  path.join(ROOT, 'src/data/parkTrails.js'),
  `/* GENERATED by tools/build-park-trails.mjs. Do not edit by hand: re-run the tool.
 * The most popular hiking trails in each national park, by AllTrails' own ranking.
 * This is AllTrails' data and is always rendered with that attribution. */

export const TRAILS_SOURCE = ${JSON.stringify(
    { name: 'AllTrails', url: 'https://www.alltrails.com/', sort: src.sort, checkedOn: src.checkedOn },
    null,
    2,
  )}

export const UNRANKED_PARKS = ${JSON.stringify(unranked)}

export const PARK_TRAILS = ${JSON.stringify(out, null, 2)}
`,
)
console.log(`park trails: ${kept} trails across ${Object.keys(out).length} parks`)
